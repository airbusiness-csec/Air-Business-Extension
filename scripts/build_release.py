"""Builds releases/air-business-xslt-polyfill-<version>.zip.

    python scripts/build_release.py [--force]

Also regenerates README.html and checks the bundle and manifest files first.
"""

import hashlib
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_readme_html  # noqa: E402

RELEASES = ROOT / "releases"

RELEASE_FILES = [
    "manifest.json",
    "background.js",
    "detect.js",
    "scope.js",
    "popup.html",
    "popup.js",
    "popup.css",
    "xslt-extension.js",
    "README.html",
    "LICENSE",
]
RELEASE_DIRS = ["icons", "docs"]

FIXED_TIME = (2025, 1, 1, 0, 0, 0)  # same zip bytes every build


def fail(message):
    print(f"Release not built: {message}", file=sys.stderr)
    sys.exit(1)


def read(name):
    return (ROOT / name).read_text(encoding="utf-8")


def check_bundle():
    # has to match what scripts/bundle.mjs writes
    expected = (
        "// Generated by scripts/bundle.mjs from content.js and xslt-polyfill.min.js. Don't edit.\n"
        f"(() => {{\n{read('content.js')}\n{read('xslt-polyfill.min.js')}\n}})();\n"
    )
    with open(ROOT / "xslt-extension.js", encoding="utf-8", newline="") as f:
        if f.read() != expected:
            fail("xslt-extension.js is out of date. Run `node scripts/bundle.mjs` first.")


def check_manifest(manifest, files):
    referenced = set()
    for cs in manifest.get("content_scripts", []):
        referenced.update(cs.get("js", []))
        referenced.update(cs.get("css", []))
    referenced.add(manifest.get("background", {}).get("service_worker"))
    action = manifest.get("action", {})
    referenced.add(action.get("default_popup"))
    referenced.update(action.get("default_icon", {}).values())
    referenced.update(manifest.get("icons", {}).values())
    referenced.discard(None)
    missing = sorted(r for r in referenced if r not in files)
    if missing:
        fail(f"manifest.json refers to files not in the release: {', '.join(missing)}")


def collect():
    files = list(RELEASE_FILES)
    for d in RELEASE_DIRS:
        files += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / d).rglob("*") if p.is_file())
    for f in files:
        if not (ROOT / f).is_file():
            fail(f"missing file: {f}")
        if f.endswith(".pem"):
            fail(f"refusing to package a private key: {f}")
    return files


def main():
    force = "--force" in sys.argv[1:]
    manifest = json.loads(read("manifest.json"))
    version = manifest["version"]

    build_readme_html.main()
    check_bundle()
    files = collect()
    check_manifest(manifest, set(files))

    RELEASES.mkdir(exist_ok=True)
    out = RELEASES / f"air-business-xslt-polyfill-{version}.zip"
    if out.exists() and not force:
        fail(
            f"{out.name} already exists. Bump \"version\" in manifest.json for a new release, "
            "or use --force to rebuild this one."
        )

    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in files:
            info = zipfile.ZipInfo(f, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, (ROOT / f).read_bytes())

    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    (RELEASES / f"{out.name}.sha256").write_text(f"{digest}  {out.name}\n", encoding="utf-8", newline="\n")

    print(f"Built releases/{out.name} ({len(files)} files, {out.stat().st_size // 1024} KB)")
    print(f"SHA-256: {digest}")


if __name__ == "__main__":
    main()
