// Builds xslt-extension.js from content.js + xslt-polyfill.min.js, wrapped so
// nothing leaks into the page's globals. Rerun after changing either.
import fs from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (file) => fs.readFileSync(new URL(file, root), 'utf8');

const polyfill = read('xslt-polyfill.min.js');
if (!polyfill.includes('xsltPolyfillOptions')) {
  throw new Error("xslt-polyfill.min.js doesn't support xsltPolyfillOptions; update it first.");
}
fs.writeFileSync(
  new URL('xslt-extension.js', root),
  `// Generated by scripts/bundle.mjs from content.js and xslt-polyfill.min.js. Don't edit.
(() => {
${read('content.js')}
${polyfill}
})();
`,
);
